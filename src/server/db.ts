  // Helper method to compute statistics
  public getStats(): PortalStats {
    const totalIdeas = this.ideas.length;
    const activeChallenges = this.problemStatements.filter(p => p.status === 'Open' || p.status === 'Under Evaluation').length;
    const registeredVendors = this.vendors.length;
    const proposalsReceived = this.proposals.length;
    const pocsUnderExecution = this.projects.filter(p => p.currentStage === 'PoC').length;
    const projectsUnderImplementation = this.projects.filter(p => p.currentStage === 'Implementation' || p.currentStage === 'Pilot').length;
    const projectsCompleted = this.projects.filter(p => p.currentStage === 'Benefits Realisation' || p.currentStage === 'Closure' || p.health === 'Completed').length;
    
    // Sum benefits
    let estimatedAnnualSavingsCr = 0;
    let realisedSavingsCr = 0;
    for (const proj of this.projects) {
      for (const b of proj.benefits) {
        estimatedAnnualSavingsCr += b.projectedAnnualCr;
        realisedSavingsCr += b.realisedAnnualCr;
      }
    }

    return {
      totalIdeas,
      activeChallenges,
      registeredVendors,
      proposalsReceived,
      pocsUnderExecution,
      projectsUnderImplementation,
      projectsCompleted,
      estimatedAnnualSavingsCr: Math.round(estimatedAnnualSavingsCr * 100) / 100,
      realisedSavingsCr: Math.round(realisedSavingsCr * 100) / 100,
      aiSolutionsImplemented: 4,
    };
  }

